"""Rebuild the approved offline aggregate from the same read adapter as the API."""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app.published_months import published_month_results


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Verify without writing")
    args = parser.parse_args()
    try:
        payload = {
            "schema_version": "ocean-offline-published-months/v1",
            "public_aggregate_allowed": True,
            "results": published_month_results(),
        }
        content = (
            "/* CC0 authored synthetic aggregates; generated by the published A read adapter. */\n"
            "window.OceanPublishedMonths = "
            + json.dumps(payload, ensure_ascii=False, indent=2)
            + ";\n"
        )
        target = ROOT / "frontend/prototype/data/published-months.js"
        if args.check:
            if target.read_text(encoding="utf-8") != content:
                raise ValueError("Published aggregate drift")
        else:
            target.write_text(content, encoding="utf-8")
        print(
            "Public offline monthly projection verified"
            if args.check
            else "Public offline monthly projection exported"
        )
    except (OSError, ValueError, TypeError, KeyError):
        raise SystemExit(
            "Published aggregate unavailable or inconsistent; no fallback generated"
        ) from None


if __name__ == "__main__":
    main()
