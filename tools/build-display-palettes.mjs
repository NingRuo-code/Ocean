import { readFile, writeFile, readdir } from "node:fs/promises";
import { createHash } from "node:crypto";

const hash = text => createHash("sha256").update(text).digest("hex");
const palettes = {};
for (const name of ["cmocean_thermal", "MPL_Purples"]) {
  const raw = await readFile(`frontend/prototype/palettes/${name}.rgb`, "utf8");
  const rows = raw.split(/\r?\n/).filter(line => /^\s*\d+(?:\.\d+)?\s+\d/.test(line)).map(line => line.trim().split(/\s+/).map(Number));
  const expected = Number(raw.match(/ncolors\s*=\s*(\d+)/)?.[1]);
  if (rows.length !== expected || rows.some(row => row.length !== 3 || row.some(n => !Number.isFinite(n) || n < 0 || n > 255))) throw Error(`Invalid palette: ${name}`);
  const normalized = rows.every(row => row.every(n => n <= 1));
  palettes[name] = { colors: rows.map(row => "#" + row.map(n => Math.round(n * (normalized ? 255 : 1)).toString(16).padStart(2, "0")).join("")),
    source: `https://www.ncl.ucar.edu/Document/Graphics/ColorTables/Files/${name}.rgb`, sha256: hash(raw) };
}
const sources = [], dates = [], domain = [Infinity, -Infinity];
let product = null, binC = null, bbox = [Infinity, Infinity, -Infinity, -Infinity];
for (const file of (await readdir("frontend/prototype/data/sst")).filter(f => /^\d{4}-\d{2}-\d{2}\.js$/.test(f)).sort()) {
  const bytes = await readFile(`frontend/prototype/data/sst/${file}`), text = bytes.toString("utf8");
  const payload = JSON.parse(text.match(/\["\d{4}-\d{2}-\d{2}"\]\s*=\s*(\{.*\})\s*;/s)?.[1] || "null");
  if (!payload || !Number.isFinite(payload.bin_c) || payload.bin_c <= 0 || !payload.runs.length) throw Error(`Invalid SST: ${file}`);
  const identity = { id: payload.product.id, version: payload.product.version };
  if (product && (JSON.stringify(product) !== JSON.stringify(identity) || binC !== payload.bin_c)) throw Error("Mixed SST product or encoding");
  product = identity; binC = payload.bin_c;
  const g = payload.grid;
  bbox = [Math.min(bbox[0], g.lon0), Math.min(bbox[1], g.lat0), Math.max(bbox[2], g.lon0 + (g.nx - 1) * g.dlon), Math.max(bbox[3], g.lat0 + (g.ny - 1) * g.dlat)];
  for (const run of payload.runs) {
    const v = run[3] * payload.bin_c;
    if (!Number.isFinite(v)) throw Error(`Invalid SST bin: ${file}`);
    domain[0] = Math.min(domain[0], v); domain[1] = Math.max(domain[1], v);
  }
  // Archive JS is text; hash canonical LF to avoid OS checkout-dependent versions.
  dates.push(payload.date); sources.push({ file, sha256: hash(text.replace(/\r\n/g, "\n")) });
}
if (!sources.length) throw Error("No SST scope to audit");
if (!(domain[0] < domain[1])) throw Error("SST needs a nonconstant reference domain");
const manifest = { schema: "ocean-display-domains/v1", sst: { status: "scoped", version: "sst-export/" + hash(JSON.stringify(sources)).slice(0, 12),
  domain, dates, product, bin_c: binC, bbox: bbox.map(n => +n.toFixed(6)), source_hash_encoding: "utf8-lf", sources,
  note: "Encoded export-bin extent, limited to the listed archive files; not a yearly or research-domain qualification." },
  effort: { status: "pending", domain: null, note: "No verified fixed scope of activity hours is registered; do not use a mock-up or daily extrema as a quantitative scale." } };
await writeFile("frontend/prototype/palettes/palettes.js", "// Generated by tools/build-display-palettes.mjs from the preserved NCL numeric tables.\nwindow.OF_PALETTES = " + JSON.stringify(palettes) + ";\n");
await writeFile("frontend/prototype/data/display-domains.js", "// Generated by tools/build-display-palettes.mjs; do not hand-edit or promote to research qualification.\nwindow.OF_DISPLAY_DOMAINS = " + JSON.stringify(manifest, null, 2) + ";\n");
console.log(JSON.stringify({ palette_rows: Object.fromEntries(Object.entries(palettes).map(([k, v]) => [k, v.colors.length])), sst_domain: domain, files: sources.length, effort: "pending" }));
